def load_settings() -> dict:
    """Wczytuje preferencje użytkownika z pliku settings.json."""
    if os.path.exists(SETTINGS_FILE):
        try:
            with open(SETTINGS_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return {"lang": "pl"}


def save_settings(settings: dict):
    """Zapisuje preferencje użytkownika do settings.json."""
    try:
        with open(SETTINGS_FILE, "w", encoding="utf-8") as f:
            json.dump(settings, f, indent=2, ensure_ascii=False)
    except Exception:
        pass


def t(key: str, lang: str = "pl") -> str:
    """Zwraca przetłumaczony ciąg znaków dla podanego klucza i języka."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["pl"])
    return lang_dict.get(key, TRANSLATIONS["pl"].get(key, key))
